package caseapp.core.app

import caseapp.core.app.nio._
import caseapp.core.commandparser.RuntimeCommandParser
import caseapp.core.complete.{
  Bash,
  CompletionItem,
  CompletionsInstallOptions,
  CompletionsUninstallOptions,
  Fish,
  Zsh
}

/** Entry point of an application with several commands
  *
  * Extend it with an `object`, and define [[progName]] and [[commands]]. Its [[main]] method looks
  * for the command to run from the command-line arguments (see [[commandFor]]), and runs it with
  * the arguments that follow the command name. If no command matches, and there's no
  * [[defaultCommand]], it prints the help message of the application, listing its commands.
  *
  * {{{
  * object MyApp extends CommandsEntryPoint {
  *   def progName = "my-app"
  *   def commands = Seq(Add, Remove) // Add and Remove extend Command
  *   override def description = "Manages things"
  * }
  * }}}
  *
  * It can also provide shell completions (for bash, zsh, and fish) for the application, its
  * commands, and their options, if [[enableCompleteCommand]] and [[enableCompletionsCommand]] are
  * set to `true`. Users can then install completions in their shell with `my-app completions
  * install`.
  *
  * See `caseapp.catseffect.IOCommandsEntryPoint` in the case-app-cats module for a cats-effect
  * version of this class.
  */
abstract class CommandsEntryPoint extends CommandsEntryPointLike[Command[_]] {

  /** Whether to enable the `complete` command, that computes shell completions
    *
    * `false` by default. This command is the one called by the completion scripts installed with
    * the `completions` command (see [[enableCompletionsCommand]]), so it needs to be enabled for
    * completions to work. It's run like `my-app complete zsh-v1 2 my-app --`, see [[completeMain]].
    */
  def enableCompleteCommand: Boolean = false

  /** Name of the `complete` command, see [[enableCompleteCommand]]
    *
    * `complete` by default. Note that the completion scripts generated by case-app always call the
    * `complete` command, whatever this name.
    */
  def completeCommandName: List[String] = List("complete")

  /** Whether to enable the `completions` command, that installs, uninstalls, or prints the
    * completion scripts of the application
    *
    * `false` by default. See [[completionsMain]] for its usage. The installed scripts rely on the
    * `complete` command, see [[enableCompleteCommand]].
    */
  def enableCompletionsCommand: Boolean = false

  /** Name of the `completions` command, see [[enableCompletionsCommand]]
    *
    * `completions` by default. Used in the instructions printed by this command.
    */
  def completionsCommandName: List[String] = List("completions")

  /** Names under which the `completions` command is accepted
    *
    * Defaults to [[completionsCommandName]] and `completion`.
    */
  def completionsCommandAliases: List[List[String]] = List(
    completionsCommandName,
    List("completion")
  )

  /** Prints instructions on how to install completions, on stderr */
  def completionsPrintInstructions(): Unit = {
    printLine("To install completions, run", toStderr = true)
    printLine("", toStderr = true)
    printLine(
      s"  $progName ${completionsCommandName.mkString(" ")} install",
      toStderr = true
    )
    printLine("", toStderr = true)
  }

  /** Prints instructions on how to use the `complete` command */
  def completePrintInstructions(toStderr: Boolean): Unit = {
    val formats = Seq(Bash.id, Zsh.id, Fish.id)
    printLine("To manually get completions, run", toStderr = toStderr)
    printLine("", toStderr = toStderr)
    printLine(
      s"  $progName ${completeCommandName.mkString(" ")} ${formats.mkString("|")} index command...",
      toStderr = toStderr
    )
    printLine("", toStderr = toStderr)
    printLine(
      "where index starts from one, and command... includes the command name, like",
      toStderr = toStderr
    )
    printLine("", toStderr = toStderr)
    printLine(
      s"  $progName ${completeCommandName.mkString(" ")} ${Zsh.id} 2 $progName --",
      toStderr = toStderr
    )
    printLine("", toStderr = toStderr)
    printLine("to get completions for '--'", toStderr = toStderr)
  }

  /** Called when the arguments of the `completions` command aren't recognized
    *
    * Prints instructions (see [[completionsPrintInstructions]]), and exits with exit code 1.
    */
  def completionsPrintUsage(): Nothing = {
    completionsPrintInstructions()
    exit(1)
  }

  /** Called when an unrecognized completion format or shell is passed to the `complete` or
    * `completions` commands
    *
    * Prints an error message on stderr, and exits with exit code 1.
    */
  def completeUnrecognizedFormat(format: String): Nothing = {
    printLine(s"Unrecognized completion format '$format'", toStderr = true)
    exit(1)
  }

  /** Directory where the zsh completion script is written, when installing completions
    *
    * If set, the script is written in its `zsh` sub-directory. `None` by default, in which case the
    * script is written in `zsh/completions` under [[completionXdgHome]], or under the `.config`
    * directory of [[completionZDotDir]] or of [[completionHome]]. The `--output` option of
    * `completions install` takes precedence over it.
    */
  def completionsWorkingDirectory: Option[String] = None

  /** Called first by [[completeMain]], with its arguments
    *
    * By default, if the `CASEAPP_COMPLETION_DEBUG` environment variable is set (see
    * [[completionDebugFile]]), appends the arguments to the file it points to, to help debugging
    * completions.
    */
  protected def completeMainHook(args: Array[String]): Unit =
    for (path <- completionDebugFile) {
      val output = s"completeMain(${args.toSeq})"
      FileOps.appendToFile(path, output)
    }

  /** Message printed on stderr after installing completions
    *
    * @param rcFile
    *   shell configuration file that was updated, or that already contained the completions
    * @param updated
    *   whether `rcFile` was updated, or already up-to-date
    */
  def completionsInstalledMessage(
    rcFile: String,
    updated: Boolean
  ): Iterator[String] = {
    val q = "\""
    val evalCommand =
      s"eval $q$$($progName ${completionsCommandName.mkString(" ")} install --env)$q"
    if (updated)
      Iterator(
        s"Updated $rcFile",
        "",
        s"It is recommended to reload your shell, or source $rcFile in the " +
          "current session, for its changes to be taken into account.",
        "",
        "Alternatively, enable completions in the current session with",
        "",
        s"  $evalCommand",
        ""
      )
    else
      Iterator(
        s"$rcFile already up-to-date.",
        "",
        "If needed, enable completions in the current session with",
        "",
        s"  $evalCommand",
        ""
      )
  }

  /** Shell of the user, used to pick the completion format when installing completions with no
    * `--shell` option
    *
    * Defaults to the `SHELL` environment variable.
    */
  def shell: Option[String] = FileOps.readEnv("SHELL")

  /** Home directory, where shell configuration files are looked for when installing completions
    */
  def completionHome: Path = FileOps.homeDir

  /** XDG configuration directory, defaults to the `XDG_CONFIG_HOME` environment variable
    *
    * Used to compute where the zsh and fish completion scripts are written.
    */
  def completionXdgHome: Option[Path] = FileOps.readEnv("XDG_CONFIG_HOME").map(Paths.get(_))

  /** zsh configuration directory, defaults to the `ZDOTDIR` environment variable
    *
    * If set, the `.zshrc` file is looked for there, rather than in [[completionHome]].
    */
  def completionZDotDir: Option[Path] = FileOps.readEnv("ZDOTDIR").map(Paths.get(_))

  /** File where the arguments of the `complete` command are written, to debug completions
    *
    * Defaults to the `CASEAPP_COMPLETION_DEBUG` environment variable. See [[completeMainHook]].
    */
  def completionDebugFile: Option[Path] =
    FileOps.readEnv("CASEAPP_COMPLETION_DEBUG").map(Paths.get(_))

  private def fishRcFile(name: String): Path =
    completionXdgHome
      .getOrElse(completionHome.resolve(".config"))
      .resolve("fish")
      .resolve("completions")
      .resolve(s"$name.fish")

  private def zshrcFile: Path =
    completionZDotDir
      .getOrElse(completionHome)
      .resolve(".zshrc")
  private def bashrcFile: Path =
    completionHome.resolve(".bashrc")

  private def zshCompletionWorkingDir(forcedOutputDir: Option[String]): Path =
    forcedOutputDir
      .orElse(completionsWorkingDirectory)
      .map(Paths.get(_).resolve("zsh"))
      .getOrElse {
        val zDotDir = completionZDotDir.getOrElse(completionHome)
        completionXdgHome
          .getOrElse(zDotDir.resolve(".config"))
          .resolve("zsh")
          .resolve("completions")
      }

  // Adapted from https://github.com/VirtusLab/scala-cli/blob/eced0b35c769eca58ae6f1b1a3be0f29a8700859/modules/cli/src/main/scala/scala/cli/commands/installcompletions/InstallCompletions.scala
  /** Installs completions, run by `completions install`
    *
    * The completion format is the one passed with `--shell`, or is guessed from [[shell]]. With
    * `--env`, the shell code enabling completions is printed on stdout. Else, it is added to the
    * shell configuration file: `~/.bashrc` for bash, `.zshrc` for zsh (in [[completionZDotDir]] or
    * [[completionHome]]), or `--rc-file`. For zsh, the completion script itself is written in a
    * directory added to `fpath` (see [[completionsWorkingDirectory]]). For fish, the completion
    * script is written in `fish/completions` under [[completionXdgHome]] (or `~/.config`), or under
    * `--output`.
    */
  def completionsInstall(
    completionsWorkingDirectory: Option[String],
    options: CompletionsInstallOptions
  ): Unit = {
    val name = options.name.getOrElse(Paths.get(progName).getFileName.toString)
    val format = CommandsEntryPoint.getFormat(options.format, shell, File.separator).getOrElse {
      printLine(
        "Cannot determine current shell, pass the shell you use with --shell, like",
        toStderr = true
      )
      printLine("", toStderr = true)
      for (shell <- Seq(Bash.shellName, Zsh.shellName, Fish.shellName))
        printLine(
          s"  $name ${completionsCommandName.mkString(" ")} install --shell $shell",
          toStderr = true
        )
      printLine("", toStderr = true)
      exit(1)
    }

    val (rcScript, defaultRcFile) = format match {
      case Bash.id | Bash.shellName =>
        (Bash.script(name), bashrcFile)
      case Fish.id | Fish.shellName =>
        (Fish.script(name), fishRcFile(name))
      case Zsh.id | Zsh.shellName =>
        val completionScript     = Zsh.script(name)
        val dir                  = zshCompletionWorkingDir(options.output)
        val completionScriptDest = dir.resolve(s"_$name")
        val needsWrite = !FileOps.exists(completionScriptDest) ||
          FileOps.readFile(completionScriptDest) != completionScript
        if (needsWrite) {
          printLine(s"Writing $completionScriptDest")
          FileOps.createDirectories(completionScriptDest.getParent)
          FileOps.writeFile(completionScriptDest, completionScript)
        }
        val script = Seq(s"""fpath=("$dir" $$fpath)""", "compinit")
          .map(_ + System.lineSeparator())
          .mkString
        (script, zshrcFile)
      case _ =>
        printLine(s"Unrecognized or unsupported shell: $format", toStderr = true)
        exit(1)
    }

    if (options.env)
      println(rcScript)
    else {
      val rcFile = format match {
        case Fish.id | Fish.shellName =>
          options.output.map(Paths.get(_)).map(_.resolve(s"$name.fish")).getOrElse(defaultRcFile)
        case _ =>
          options.rcFile.map(Paths.get(_)).getOrElse(defaultRcFile)
      }
      val banner  = options.banner.replace("{NAME}", name)
      val updated = ProfileFileUpdater.addToProfileFile(rcFile, banner, rcScript)

      for (line <- completionsInstalledMessage(rcFile.toString, updated))
        printLine(line, toStderr = true)
    }
  }

  /** Uninstalls completions, run by `completions uninstall`
    *
    * Removes the section added by [[completionsInstall]] from the shell configuration files
    * (`~/.zshrc` and `~/.bashrc`, or `--rc-file`), and deletes the zsh and fish completion scripts.
    */
  def completionsUninstall(
    completionsWorkingDirectory: Option[String],
    options: CompletionsUninstallOptions
  ): Unit = {
    val name = options.name.getOrElse(Paths.get(progName).getFileName.toString)

    val rcFiles = options.rcFile
      .map(file => Seq(Paths.get(file)))
      .getOrElse(Seq(zshrcFile, bashrcFile))
      .filter(FileOps.exists(_))

    val maybeDelete = Seq(
      zshCompletionWorkingDir(options.output).resolve(s"_$name"),
      fishRcFile(name)
    )

    for (rcFile <- rcFiles) {
      val banner = options.banner.replace("{NAME}", name)

      val updated = ProfileFileUpdater.removeFromProfileFile(rcFile, banner)

      if (updated) {
        printLine(s"Updated $rcFile", toStderr = true)
        printLine(s"$name completions uninstalled successfully", toStderr = true)
      }
      else
        printLine(s"No $name completion section found in $rcFile", toStderr = true)
    }

    for (f <- maybeDelete)
      if (FileOps.isRegularFile(f)) {
        val deleted = FileOps.deleteIfExists(f)
        if (deleted)
          printLine(s"Removed $f", toStderr = true)
      }
  }

  /** Runs the `completions` command, with the arguments that follow its name
    *
    * Accepts:
    *   - `install [options]`: installs completions, see [[completionsInstall]] and
    *     [[caseapp.core.complete.CompletionsInstallOptions]],
    *   - `uninstall [options]`: uninstalls completions, see [[completionsUninstall]] and
    *     [[caseapp.core.complete.CompletionsUninstallOptions]],
    *   - `<shell>`: prints the completion script for `<shell>` (`bash`, `zsh`, or `fish`),
    *   - `<shell> <file>`: writes the completion script for `<shell>` to `<file>`.
    */
  def completionsMain(args: Array[String]): Unit = {

    def script(format: String): String =
      format match {
        case Bash.shellName | Bash.id => Bash.script(progName)
        case Fish.shellName | Fish.id => Fish.script(progName)
        case Zsh.shellName | Zsh.id   => Zsh.script(progName)
        case _ =>
          completeUnrecognizedFormat(format)
      }

    args match {
      case Array("install", args0 @ _*) =>
        val (options, rem) = CaseApp.process[CompletionsInstallOptions](args0)
        if (rem.all.nonEmpty)
          sys.error(s"Unexpected arguments passed to completions install: ${rem.all.mkString(" ")}")
        completionsInstall(completionsWorkingDirectory, options)
      case Array("uninstall", args0 @ _*) =>
        val (options, rem) = CaseApp.process[CompletionsUninstallOptions](args0)
        completionsUninstall(completionsWorkingDirectory, options)
      case Array(format, dest) =>
        val script0 = script(format)
        FileOps.writeFile(Paths.get(dest), script0)
      case Array(format) =>
        val script0 = script(format)
        printLine(script0)
      case _ =>
        completionsPrintUsage()
    }
  }

  /** Computes completions, for command names and for the arguments of commands
    *
    * @param args
    *   arguments of the application (without the program name)
    * @param index
    *   index in `args` of the argument to complete
    */
  def complete(args: Seq[String], index: Int): List[CompletionItem] =
    defaultCommand match {
      case None =>
        RuntimeCommandParser.complete(commands, args.toList, index)
      case Some(defaultCommand0) =>
        RuntimeCommandParser.complete(defaultCommand0, commands, args.toList, index)
    }

  /** Runs the `complete` command, with the arguments that follow its name
    *
    * Expects arguments like `<format> <index> <program-name> <args…>`, where `<format>` is a
    * completion format (`bash-v1`, `zsh-v1`, or `fish-v1`), and `<index>` is the index of the
    * argument to complete, starting from 1 for the program name. Prints the completions in the
    * format expected by the completion scripts of the corresponding shell.
    */
  def completeMain(args: Array[String]): Unit = {
    completeMainHook(args)
    args match {
      case Array(format, indexStr, userArgs @ _*) =>
        val index          = indexStr.toInt - 2 // -1 for argv[0], and -1 as indices start at 1
        val prefix: String = userArgs.applyOrElse(index + 1, (_: Int) => "")
        val items = complete(userArgs.toList.drop(1), index)
          .flatMap { item =>
            val values = item.values.filter(_.startsWith(prefix))
            if (values.isEmpty) Nil
            else Seq(CompletionItem(values.head, item.description, values.tail.toList))
          }
        format match {
          case Bash.id =>
            printLine(Bash.print(items))
          case Fish.id =>
            printLine(Fish.print(items))
          case Zsh.id =>
            printLine(Zsh.print(items))
          case _ =>
            completeUnrecognizedFormat(format)
        }
      case Array("--help" | "--usage" | "-h") =>
        completePrintInstructions(toStderr = false)
      case _ =>
        completePrintInstructions(toStderr = true)
        exit(1)
    }
  }

  /** Exits the application, see [[CaseApp.exit]] */
  def exit(code: Int): Nothing =
    PlatformUtil.exit(code)

  /** Prints a line, on stdout or on stderr, see `CaseApp#printLine` */
  def printLine(line: String, toStderr: Boolean): Unit =
    if (toStderr)
      System.err.println(line)
    else
      println(line)

  /** Prints a line on stdout */
  final def printLine(line: String): Unit =
    printLine(line, toStderr = false)

  /** Called when no command matches the arguments, and there's no [[defaultCommand]]
    *
    * Prints the help message of the application, and exits with exit code 0.
    */
  def printUsage(): Nothing = {
    val usage = help.help(helpFormat, showHidden = false)
    printLine(usage)
    exit(0)
  }

  /** Entry point of the application
    *
    * Runs the `complete` or `completions` commands if they are enabled and asked, else finds the
    * command to run (see [[commandFor]]) and calls its `main(progName, args)` method, or calls
    * [[printUsage]] if no command matches.
    */
  def main(args: Array[String]): Unit = {
    val actualArgs = PlatformUtil.arguments(args)
    if (enableCompleteCommand && actualArgs.startsWith(completeCommandName.toArray[String]))
      completeMain(actualArgs.drop(completeCommandName.length))
    else {
      val completionAliasOpt =
        if (enableCompletionsCommand) completionsCommandAliases.find(actualArgs.startsWith(_))
        else None
      completionAliasOpt match {
        case Some(completionAlias) =>
          completionsMain(actualArgs.drop(completionAlias.length))
        case None =>
          commandFor(actualArgs.toList) match {
            case None =>
              printUsage()
            case Some((commandProgName, command, commandArgs)) =>
              command.main(commandProgName, commandArgs.toArray)
          }
      }
    }
  }
}

object CommandsEntryPoint {

  /** Completion format to use, from the `--shell` option if passed, else guessed from the shell
    * path (like `/bin/zsh`)
    */
  def getFormat(format: Option[String], shellOpt: Option[String], fileSep: String): Option[String] =
    format.map(_.trim).filter(_.nonEmpty)
      .orElse {
        shellOpt.map(_.split(fileSep).last).map {
          case Bash.shellName => Bash.id
          case Fish.shellName => Fish.id
          case Zsh.shellName  => Zsh.id
          case other          => other
        }
      }
}
